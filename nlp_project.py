def evaluate_descriptive(correct_answer, student_answer, max_marks):

    prompt = f"""
You are evaluating a student's exam answer.

Correct Answer:
{correct_answer}

Student Answer:
{student_answer}

Maximum Marks: {max_marks}

Tasks:
1. Compute semantic similarity between the two answers (0.0 to 1.0).
2. Assign marks out of {max_marks} proportional to conceptual correctness.

Rules:
- Accept synonyms, paraphrasing, and equivalent scientific terms
- Ignore spelling and grammar mistakes
- Award partial marks for partially correct answers
- Similarity must reflect conceptual overlap, not just word matching
- If student answer covers all key points → marks close to {max_marks}
- If student answer is partially correct → proportional marks
- If student answer is completely wrong or irrelevant → marks = 0

Return ONLY this JSON (no markdown, no explanation):
{{
  "similarity": <float 0.0 to 1.0>,
  "marks": <float 0.0 to {max_marks}>
}}
"""

    response = client_llm.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": "You are a strict but fair exam evaluator. Return only valid JSON."},
            {"role": "user", "content": prompt}
        ],
        temperature=0
    )

    reply = response.choices[0].message.content.strip()

    # Remove markdown if present
    if reply.startswith("```"):
        reply = reply.split("```")[1]
        if reply.startswith("json"):
            reply = reply[4:]
        reply = reply.strip()

    try:

        data = json.loads(reply)

        similarity = max(0.0, min(1.0, float(data["similarity"])))

        raw_marks = max(0.0, min(float(max_marks), float(data["marks"])))

        # Apply ceiling but ensure it does not exceed max marks
        obtained = min(max_marks, math.ceil(raw_marks))

    except Exception as e:

        print(f"⚠️ LLM parse error: {e} | Raw reply: {reply}")
        similarity = 0.0
        obtained = 0.0

    return similarity, obtained


