from bert_score import score as bert_score
from transformers import pipeline

nli = pipeline("text-classification", model="cross-encoder/nli-deberta-v3-small")

def evaluate_descriptive_opensource_1(correct_answer, student_answer, max_marks):

    # ── Component 1: BERTScore (keyword/concept coverage) ──
    _, _, F1 = bert_score(
        [student_answer],
        [correct_answer],
        lang="en",
        model_type="bert-base-uncased",
        verbose=False
    )
    bertscore_f1 = float(F1[0])

    # ── Component 2: NLI (logical entailment) ──────────────
    nli_result = nli(f"{student_answer} [SEP] {correct_answer}")[0]
    label      = nli_result["label"]
    score      = nli_result["score"]

    if label == "ENTAILMENT":
        nli_score = score
    elif label == "NEUTRAL":
        nli_score = score * 0.5
    else:
        nli_score = 0.0

    # ── Weighted combination ────────────────────────────────
    # BERTScore: did student cover the concepts?
    # NLI:       did student answer logically match the scheme?
    similarity = (0.5 * bertscore_f1) + (0.5 * nli_score)
    obtained   = round(similarity * max_marks, 2)

    print(f"    BERTScore F1 : {bertscore_f1:.3f}")
    print(f"    NLI score    : {nli_score:.3f}  ({label})")
    print(f"    Combined     : {similarity:.3f}")

    return float(similarity), obtained

