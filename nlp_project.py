def get_student_answer(q):

    whole = q.get("whole_answer", "").strip()

    if whole:
        return whole, "whole_answer"

    parts = []

    for sub in q.get("sub_questions", []):
        sub_ans = sub.get("whole_answer", "").strip()
        sub_no = sub.get("sub_question_no") or sub.get("question_no", "")

