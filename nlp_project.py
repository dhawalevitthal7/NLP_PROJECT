def get_embedding(text):
    inputs = tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=512)
    with torch.no_grad():
        outputs = model(**inputs)
    return outputs.last_hidden_state[:, 0, :].squeeze().tolist()


def get_scheme_answer(q):
    """
    Build the full answer text for a question.
    Priority: whole_answer → concatenate sub_questions[].answer
    Marking scheme uses 'answer' key inside sub_questions (NOT 'whole_answer')
    """
    whole = q.get("whole_answer", "").strip()
    if whole:
        return whole

    parts = []
    for sub in q.get("sub_questions", []):
        sub_ans = sub.get("answer", "").strip()          # ✅ scheme uses 'answer' key
        sub_no  = sub.get("sub_question_no", "")
        if sub_ans:
            parts.append(f"({sub_no}) {sub_ans}")

    return " | ".join(parts) if parts else ""


