def merge_questions(questions):
    """
    If the same question_no appears more than once (split across page batches),
    merge their sub_questions and whole_answer.
    """
    merged = {}

    for q in questions:
        q_no = q.get("question_no")

        if q_no not in merged:
            merged[q_no] = q
        else:
            existing = merged[q_no]

            # Merge sub_questions — avoid duplicates by sub_question_no
            existing_subs = {s["sub_question_no"]: s for s in existing.get("sub_questions", [])}
            for sub in q.get("sub_questions", []):
                sub_no = sub["sub_question_no"]
                if sub_no not in existing_subs:
                    existing_subs[sub_no] = sub
                else:
                    # Append text if same sub appears again (page overlap)
                    if sub["whole_answer"] not in existing_subs[sub_no]["whole_answer"]:
                        existing_subs[sub_no]["whole_answer"] += " " + sub["whole_answer"]

            existing["sub_questions"] = list(existing_subs.values())

            # Merge whole_answer
            new_whole = q.get("whole_answer", "").strip()
            if new_whole and new_whole not in existing.get("whole_answer", ""):
                existing["whole_answer"] = (existing.get("whole_answer", "") + " " + new_whole).strip()

    # Sort by question number
    return [merged[k] for k in sorted(merged.keys())]


